// Writes one Svelte wrapper per lucide icon the docs site imports directly, so the site chrome draws Phosphor instead.
// Duotone is the default weight; arrows, carets, plus, check, x, minus and text-format icons are bold (Another UI's rule).
// The vite plugin in vite.config.ts points `@lucide/svelte/icons/<name>` at these files. The map is lucide-to-phosphor.json.
import fs from "node:fs";
import path from "node:path";

const dir = path.resolve("src/lib/components/icons");
const map = JSON.parse(fs.readFileSync(path.join(dir, "lucide-to-phosphor.json"), "utf8"));
const BOLD = /^(arrow-|chevron|plus$|check$|x$|minus$|corner-|case-upper|align-|text-)/;
fs.mkdirSync(path.join(dir, "phosphor"), { recursive: true });
for (const [lucide, phosphor] of Object.entries(map)) {
	const weight = BOLD.test(lucide) ? "bold" : "duotone";
	fs.writeFileSync(
		path.join(dir, "phosphor", `${lucide}.svelte`),
		`<!-- Generated by scripts/build-phosphor-wrappers.mjs from lucide-to-phosphor.json -->
<script lang="ts">
	import Icon from "phosphor-svelte/lib/${phosphor}";
	import type { ComponentProps } from "svelte";

	let { weight = "${weight}", ...rest }: ComponentProps<typeof Icon> = $props();
</script>

<Icon {weight} {...rest} />
`
	);
}
console.log(`wrote ${Object.keys(map).length} wrappers`);
